function formatDate(dateStr) {
    if (!dateStr) return '';
    try {
        const date = new Date(dateStr);
        return date.toLocaleDateString('en-US', { month: 'long', year: 'numeric' });
    } catch {
        return dateStr;
    }
}

function renderTableOfContents() {
    let html = '';

    publicationData.chapters.forEach((chapter, index) => {
        // H2 sub-items, revealed via CSS when this chapter is active
        let subHtml = '';
        if (chapter.sections.length > 0) {
            subHtml = '<ul class="toc-sub">';
            chapter.sections.forEach((section, sectionIndex) => {
                subHtml += `
                    <li><a href="#${chapter.id}"
                           onclick="openAnalysisPanel(${index}, ${sectionIndex}); return false;">
                        ${section.title}
                    </a></li>
                `;
            });
            subHtml += '</ul>';
        }

        html += `
            <li class="toc-item" data-chapter="${index}">
                <span class="toc-marker" aria-hidden="true"></span>
                <div class="toc-item-row">
                    <span class="toc-num">${String(index + 1).padStart(2, '0')}</span>
                    <a href="#${chapter.id}"
                       class="toc-link"
                       data-chapter="${index}"
                       onclick="scrollToChapter('${chapter.id}'); return false;">
                        ${chapter.title}
                    </a>
                </div>
                ${subHtml}
            </li>
        `;
    });

    tocList.innerHTML = html;
}

// Extract the first <p> of a rendered-HTML block, used as the card teaser
function firstParagraphOf(html) {
    const match = html.match(/<p>[\s\S]*?<\/p>/);
    return match ? match[0] : '';
}

// Estimate reading time across every layer's text (words ÷ 220 wpm)
function estimateReadingMinutes() {
    const strip = html => html.replace(/<[^>]+>/g, ' ');
    let words = 0;
    publicationData.chapters.forEach(ch => {
        words += strip(ch.content).split(/\s+/).filter(Boolean).length;
        ch.sections.forEach(s => {
            words += strip(s.content).split(/\s+/).filter(Boolean).length;
            s.subsections.forEach(sub => {
                words += strip(sub.content).split(/\s+/).filter(Boolean).length;
            });
        });
    });
    return Math.max(1, Math.round(words / 220));
}

