async function loadPublication(slug) {
    try {
        // Fetch markdown file
        const response = await fetch(`content/publications/${slug}.md`);
        if (!response.ok) {
            throw new Error(`Publication not found: ${slug}`);
        }
        const markdownText = await response.text();

        // Parse frontmatter and content
        const { metadata, content } = parseFrontmatter(markdownText);

        // Parse markdown into structured chapters
        publicationData = parseMarkdownStructure(content, metadata);

        // Update page title
        document.title = `${publicationData.title} | India AI Tracker`;

        // Render the publication
        renderPublication();

    } catch (error) {
        console.error('Error loading publication:', error);
        renderError(`Failed to load publication: ${error.message}`);
    }
}

// ============================================
// FRONTMATTER PARSING
// ============================================

function parseFrontmatter(text) {
    const frontmatterRegex = /^---\s*\n([\s\S]*?)\n---\s*\n([\s\S]*)$/;
    const match = text.match(frontmatterRegex);

    if (!match) {
        // No frontmatter, treat entire text as content
        return {
            metadata: { title: 'Untitled', author: '', date: '' },
            content: text
        };
    }

    const frontmatterText = match[1];
    const content = match[2];

    // Simple YAML parsing for flat key: value pairs
    const metadata = {};
    frontmatterText.split('\n').forEach(line => {
        const colonIndex = line.indexOf(':');
        // Only treat top-level (unindented) keys as flat fields; nested blocks
        // like takeaways are handled separately by extractTakeaways().
        if (colonIndex > 0 && !/^\s/.test(line)) {
            const key = line.substring(0, colonIndex).trim();
            let value = line.substring(colonIndex + 1).trim();
            if ((value.startsWith('"') && value.endsWith('"')) ||
                (value.startsWith("'") && value.endsWith("'"))) {
                value = value.slice(1, -1);
            }
            metadata[key] = value;
        }
    });

    // Nested "takeaways: { summary, points[] }" block (draft-preview best effort;
    // the static generator parses this with full js-yaml).
    const takeaways = extractTakeaways(frontmatterText);
    if (takeaways) metadata.takeaways = takeaways;

    return { metadata, content };
}

// Line-scan the "takeaways:" mapping for summary (inline or folded) + points list.
function extractTakeaways(frontmatterText) {
    const stripQuotes = (v) => (
        (v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))
            ? v.slice(1, -1)
            : v
    );
    const lines = frontmatterText.split('\n');
    let i = lines.findIndex(l => /^takeaways:\s*$/.test(l));
    if (i === -1) return null;

    const summaryParts = [];
    const points = [];
    let mode = null; // 'summaryFold' | 'points'

    for (i = i + 1; i < lines.length; i++) {
        const line = lines[i];
        if (line.trim() === '') continue;
        if (/^\S/.test(line)) break; // dedented to a new top-level key → block ends

        const summaryInline = line.match(/^\s{2}summary:\s*(.*)$/);
        const pointsKey = /^\s{2}points:\s*$/.test(line);
        const listItem = line.match(/^\s{2,}-\s+(.*)$/);

        if (summaryInline) {
            const v = summaryInline[1].trim();
            if (v === '' || /^[>|]-?$/.test(v)) {
                mode = 'summaryFold';
            } else {
                summaryParts.push(stripQuotes(v));
                mode = null;
            }
        } else if (pointsKey) {
            mode = 'points';
        } else if (listItem && mode === 'points') {
            points.push(stripQuotes(listItem[1].trim()));
        } else if (mode === 'summaryFold') {
            summaryParts.push(line.trim());
        }
    }

    const summary = summaryParts.join(' ').trim();
    if (!summary && points.length === 0) return null;
    return { summary, points };
}

// ============================================
// MARKDOWN STRUCTURE PARSING
// ============================================

function parseMarkdownStructure(markdown, metadata) {
    const chapters = [];
    const lines = markdown.split('\n');

    let currentH1 = null;
    let currentH2 = null;
    let currentH3 = null;
    let contentBuffer = [];

    function flushContent() {
        const html = marked.parse(contentBuffer.join('\n').trim());
        if (currentH3 && currentH2) {
            currentH3.content = html;
        } else if (currentH2 && currentH1) {
            currentH2.content += html;
        } else if (currentH1) {
            currentH1.content += html;
        }
        contentBuffer = [];
    }

    for (const line of lines) {
        if (line.startsWith('# ') && !line.startsWith('## ') && !line.startsWith('### ')) {
            // H1 - New chapter (Overview layer)
            flushContent();
            if (currentH2 && currentH1) {
                currentH1.sections.push(currentH2);
            }
            if (currentH1) {
                chapters.push(currentH1);
            }

            currentH1 = {
                id: slugify(line.substring(2)),
                title: line.substring(2).trim(),
                content: '',
                sections: []
            };
            currentH2 = null;
            currentH3 = null;

        } else if (line.startsWith('## ') && !line.startsWith('### ')) {
            // H2 - New section (Analysis layer)
            flushContent();
            if (currentH2 && currentH1) {
                currentH1.sections.push(currentH2);
            }

            currentH2 = {
                id: slugify(line.substring(3)),
                title: line.substring(3).trim(),
                content: '',
                subsections: []
            };
            currentH3 = null;

        } else if (line.startsWith('### ')) {
            // H3 - New subsection (In Depth layer)
            flushContent();
            if (currentH3 && currentH2) {
                currentH2.subsections.push(currentH3);
            }

            currentH3 = {
                id: slugify(line.substring(4)),
                title: line.substring(4).trim(),
                content: ''
            };

        } else {
            contentBuffer.push(line);
        }
    }

    // Flush remaining content
    flushContent();
    if (currentH3 && currentH2) {
        currentH2.subsections.push(currentH3);
    }
    if (currentH2 && currentH1) {
        currentH1.sections.push(currentH2);
    }
    if (currentH1) {
        chapters.push(currentH1);
    }

    return {
        title: metadata.title || 'Untitled',
        author: metadata.author || '',
        date: metadata.date || '',
        description: metadata.description || '',
        type: metadata.type || '',
        cluster: metadata.cluster || '',
        reviewed: metadata.reviewed || '',
        takeaways: (metadata.takeaways && typeof metadata.takeaways === 'object')
            ? metadata.takeaways
            : null,
        chapters
    };
}

function slugify(text) {
    return text.toLowerCase()
        .replace(/[^a-z0-9\s-]/g, '')
        .replace(/\s+/g, '-')
        .replace(/-+/g, '-')
        .replace(/^-|-$/g, '');
}

