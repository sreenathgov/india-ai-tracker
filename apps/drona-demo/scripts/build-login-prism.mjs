import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const outputDirectory = new URL("src/lib/login/generated/", root);
const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ["src/lib/login/prism.browser.js"],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  sourcemap: false,
  legalComments: "inline",
  charset: "utf8",
});
// HTML raw-text script parsing recognizes closing tags even inside a JS string.
// Escape them before embedding the bundle into the server-rendered login.
const script = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script").replace(/<!--/g, "<\\!--");
await mkdir(outputDirectory, { recursive: true });
await writeFile(new URL("prism-script.ts", outputDirectory), `// Generated by scripts/build-login-prism.mjs. Do not edit.\nexport const LOGIN_PRISM_SCRIPT = ${JSON.stringify(script)};\n`);
console.log(`Standalone login prism built (${Buffer.byteLength(script)} bytes; no runtime imports).`);
